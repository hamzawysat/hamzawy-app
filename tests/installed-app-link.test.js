'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const app = require(path.join(root, 'app.json')).expo;
const plugin = fs.readFileSync(path.join(root, 'plugins/withAssetStatements.js'), 'utf8');
const build = fs.readFileSync(path.join(root, '.github/workflows/build.yml'), 'utf8');
const ota = fs.readFileSync(path.join(root, '.github/workflows/ota-update.yml'), 'utf8');
const notifications = fs.readFileSync(path.join(root, 'src/hooks/usePushNotifications.js'), 'utf8');
assert.match(app.version, /^\d+\.\d+\.\d+$/);
assert.ok(Number.isInteger(app.android.versionCode) && app.android.versionCode > 0);
assert.ok(app.plugins.includes('./plugins/withAssetStatements'));
assert.ok(plugin.includes('https://www.hamzawy-sat.dynv6.net'));
assert.ok(plugin.includes('delegate_permission/common.handle_all_urls'));
assert.ok(plugin.includes('asset_statements'));
assert.ok(build.includes('../HSsat.apk'));
assert.ok(build.includes('path: HSsat.apk'));
assert.ok(build.includes('tag_name: ${{ env.APP_VERSION }}'));
assert.ok(ota.includes('push:\n    branches: [main]'));
assert.ok(ota.includes("github.event_name == 'push'"));
assert.equal(app.updates.enabled, true);
assert.equal(app.updates.requestHeaders['expo-channel-name'], 'production');
assert.equal(app.runtimeVersion.policy, 'appVersion');
assert.ok(JSON.stringify(app.plugins).includes('hamzawy_sat_notification_v12_wow_loud.ogg'));
assert.ok(notifications.includes("sound: 'hamzawy_sat_notification_v12_wow_loud.ogg'"));
console.log('Installed-app association, versioning, APK naming, OTA and notification-sound regression checks passed.');
